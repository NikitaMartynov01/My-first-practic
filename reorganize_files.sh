#!/bin/bash

# Скрипт для организации файлов проекта по папкам

echo "🔧 Начинаю организацию файлов..."

# Создаем основные папки
mkdir -p "Сборка_ОТВЕРТКИ"
mkdir -p "Сборка_ПЛОСКОГУБЦЫ"
mkdir -p "Сборка_ШЕСТИГРАННИКИ"
mkdir -p "Документация"

echo "📁 Папки созданы"

# Перемещаем файлы в соответствующие папки
echo "📦 Перемещаю файлы..."

# Сборка ОТВЕРТКИ
if [ -f "Сборка_ОТВЕРТКИ.stp" ]; then
    mv "Сборка_ОТВЕРТКИ.stp" "Сборка_ОТВЕРТКИ/"
    echo "✓ Сборка_ОТВЕРТКИ.stp → Сборка_ОТВЕРТКИ/"
fi

if [ -f "ФАНЕРА_ОТВЕРТКИ.cdr" ]; then
    mv "ФАНЕРА_ОТВЕРТКИ.cdr" "Сборка_ОТВЕРТКИ/"
    echo "✓ ФАНЕРА_ОТВЕРТКИ.cdr → Сборка_ОТВЕРТКИ/"
fi

# Сборка ПЛОСКОГУБЦЫ
if [ -f "Сборка_ПЛОСКОГУБЦЫ.stp" ]; then
    mv "Сборка_ПЛОСКОГУБЦЫ.stp" "Сборка_ПЛОСКОГУБЦЫ/"
    echo "✓ Сборка_ПЛОСКОГУБЦЫ.stp → Сборка_ПЛОСКОГУБЦЫ/"
fi

# Сборка ШЕСТИГРАННИКИ
if [ -f "Сборка_ШЕСТИГРАННИКИ.stp" ]; then
    mv "Сборка_ШЕСТИГРАННИКИ.stp" "Сборка_ШЕСТИГРАННИКИ/"
    echo "✓ Сборка_ШЕСТИГРАННИКИ.stp → Сборка_ШЕСТИГРАННИКИ/"
fi

if [ -f "2D_для_шестигранников.cdr" ]; then
    mv "2D_для_шестигранников.cdr" "Сборка_ШЕСТИГРАННИКИ/"
    echo "✓ 2D_для_шестигранников.cdr → Сборка_ШЕСТИГРАННИКИ/"
fi

# Документация
if [ -f "Отчет_Мартынов_НД.docx" ]; then
    mv "Отчет_Мартынов_НД.docx" "Документация/"
    echo "✓ Отчет_Мартынов_НД.docx → Документация/"
fi

# README и LICENSE остаются в корне
echo ""
echo "✅ Готово! Структура папок создана:"
echo ""
echo "📂 Структура проекта:"
echo "├── 📁 Сборка_ОТВЕРТКИ/"
echo "│   ├── Сборка_ОТВЕРТКИ.stp"
echo "│   └── ФАНЕРА_ОТВЕРТКИ.cdr"
echo "├── 📁 Сборка_ПЛОСКОГУБЦЫ/"
echo "│   └── Сборка_ПЛОСКОГУБЦЫ.stp"
echo "├── 📁 Сборка_ШЕСТИГРАННИКИ/"
echo "│   ├── Сборка_ШЕСТИГРАННИКИ.stp"
echo "│   └── 2D_для_шестигранников.cdr"
echo "├── 📁 Документация/"
echo "│   └── Отчет_Мартынов_НД.docx"
echo "├── README.md"
echo "└── LICENSE"
echo ""
echo "🎉 Все файлы организованы!"
